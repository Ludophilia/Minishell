#include <unistd.h>

void	ft_putnbr_fd(int n, int fd)
{
	if (n <= -10 || n >= 10)
		ft_putnbr_fd(n / 10, fd);
	if (n > -10 && n < 0)
		write(fd, "-", 1);
	if (n < 0)
		n = -(n % 10) + '0';
	else
		n = (n % 10) + '0';
	write(fd, &n, 1);
}
