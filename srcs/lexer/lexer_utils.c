#include "minishell.h"

int	lex_is_op(char *c)
{
	return (c[0] == '|'
		|| c[0] == '<' || c[0] == '>'
		|| c[0] == '(' || c[0] == ')'
		|| (c[0] == '&' && c[1] == '&'));
}

int	lex_is_sep(char *c)
{
	return (c[0] == ' ' || c[0] == '\t');
}

int	lex_is_quote(char *c)
{
	return (c[0] == '\'' || c[0] == '\"');
}
