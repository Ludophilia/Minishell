#include "minishell.h"

int lex_is_op(int c)
{
    return (c == '<' || c == '>' || c == '|');
}

int lex_is_sep(int c)
{
    return (c == ' ');
}

int lex_is_quote(int c)
{
    return (c == '\'' || c == '\"');
}
