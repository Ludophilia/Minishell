int	ft_atoi(const char *nptr)
{
	int	res[2];

	res[0] = 1;
	res[1] = 0;
	while ((*nptr >= 9 && *nptr <= 13) || *nptr == 32)
		++nptr;
	if (*nptr == '+' || *nptr == '-')
	{
		if (*nptr == '-')
			res[0] = -1;
		++nptr;
	}
	while (*nptr >= '0' && *nptr <= '9')
	{
		res[1] = 10 * res[1] + (*nptr - '0');
		++nptr;
	}
	return (res[0] * res[1]);
}
